"""Writes src/lib/demo-people.ts from people.py.

    python3 scripts/demo/build.py

Only people whose photos exist in public/images are written, so the app never
points at a missing picture. Run it after photos.py, then `npm run db:seed`.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from people import people  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
IMAGES = ROOT / "public" / "images"


def ready(p):
    names = [f"{p['id']}-1", f"{p['id']}-2"]
    if "room" in p:
        names += [f"{p['id']}-room-{n}" for n in (1, 2, 3)]
    return all((IMAGES / f"{n}.jpg").exists() for n in names)


def entry(p):
    pid = p["id"]
    photos = [f"/images/{pid}-1.jpg", f"/images/{pid}-2.jpg"]
    out = {
        "id": pid, "name": p["name"], "age": p["age"], "status": p["status"],
        "occupation": p["occupation"], "university": p["university"],
        "languages": p["languages"], "gender": p["gender"], "city": "Riga",
        "neighborhood": p["neighborhood"], "bio": p["bio"],
        "photo": photos[0], "photos": photos, "budget": p["budget"],
        "moveDate": f"@@moveIn({p['moveIn']})@@",
        "stayMonths": p["stayMonths"], "intent": p["intent"],
        "tags": p["tags"], "prompts": p["prompts"], "habits": p["habits"],
        "verified": p["verified"], "active": True, "likesYou": p["likesYou"],
    }
    if "room" in p:
        room = {k: v for k, v in p["room"].items() if k != "look"}
        shots = [f"/images/{pid}-room-{n}.jpg" for n in (1, 2, 3)]
        out["room"] = {
            "title": room.pop("title"), "price": room.pop("price"),
            "photo": shots[0], "photos": shots, **room,
        }
    return out


done = [entry(p) for p in people() if ready(p)]
body = json.dumps(done, ensure_ascii=False, indent=2)
body = body.replace('"@@', "").replace('@@"', "")
(ROOT / "src" / "lib" / "demo-people.ts").write_text(
    "// Generated by scripts/demo/build.py from scripts/demo/people.py.\n"
    "// Edit that file and run the script, not this one.\n"
    'import { moveIn } from "./demo-dates";\n'
    'import type { Profile } from "./types";\n\n'
    "/** More fictional demo people; their photos were generated for the demo. */\n"
    f"export const morePeople: Profile[] = {body};\n"
)
print(f"{len(done)} of {len(people())} people have all their photos.")
