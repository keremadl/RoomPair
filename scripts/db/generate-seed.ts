/**
 * Writes supabase/seed.sql from the demo people in src/lib/data.ts, so the
 * database and the browser-only demo always describe the same people.
 *
 *   npm run db:seed
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { profiles } from "../../src/lib/data";

const text = (value: string | null | undefined) =>
  value == null ? "null" : `'${value.replace(/'/g, "''")}'`;
const list = (values: string[]) =>
  `array[${values.map(text).join(", ")}]::text[]`;
const json = (value: unknown) => `${text(JSON.stringify(value))}::jsonb`;
// Stable ids, so re-seeding updates the same accounts instead of adding more.
const memberId = (index: number) =>
  `00000000-0000-4000-a000-${String(index + 1).padStart(12, "0")}`;
const roomId = (index: number) =>
  `00000000-0000-4000-b000-${String(index + 1).padStart(12, "0")}`;

const accounts = profiles
  .map(
    (p, i) =>
      `  ('${memberId(i)}'::uuid, '${p.id}@demo.roompair.example', ${text(p.name)})`,
  )
  .join(",\n");

const people = profiles
  .map(
    (
      p,
      i,
    ) => `  ('${memberId(i)}'::uuid, ${text(p.name)}, ${p.age}, ${text(p.status)}, ${text(p.occupation)}, ${text(p.university)},
   ${list(p.languages)}, ${text(p.gender)}, ${text(p.city)}, ${text(p.neighborhood)},
   ${text(p.bio)},
   ${text(p.photo)}, ${list(p.photos)}, ${list(p.tags)},
   ${json(p.prompts)},
   ${text(p.intent)}, ${p.budget[0]}, ${p.budget[1]}, date '${p.moveDate}', ${p.stayMonths},
   ${p.habits.cleanliness}, ${p.habits.social}, ${text(p.habits.sleep)}, ${p.habits.smoking}, ${p.habits.pets},
   ${text(p.habits.guests)}, ${text(p.habits.homeDays)}, ${text(p.habits.noise)}, ${text(p.habits.sharing)},
   ${p.verified}, ${p.active}, ${p.likesYou})`,
  )
  .join(",\n");

const hosts = profiles.flatMap((p, i) =>
  p.room ? [{ p, i, room: p.room }] : [],
);
const roomKeys = hosts
  .map(
    ({ p, i, room }) =>
      `  ('${roomId(i)}'::uuid, '${memberId(i)}'::uuid, ${text(room.title)}, ${room.price}, ${text(p.city)})`,
  )
  .join(",\n");
const roomDetails = hosts
  .map(
    ({ p, i, room }) => `  ('${roomId(i)}'::uuid, ${text(room.title)},
   ${text(room.description)},
   ${room.price}, ${text(room.photo)}, ${list(room.photos ?? [room.photo])}, ${text(p.city)}, ${text(p.neighborhood)},
   ${room.billsIncluded}, ${room.deposit}, ${room.privateBathroom}, ${room.furnished}, ${room.flatmates},
   ${text(room.transport)}, ${text(room.houseRules)})`,
  )
  .join(",\n");

const sql = `-- Demo accounts for RoomPair. Generated by scripts/db/generate-seed.ts from
-- src/lib/data.ts; edit that file and run \`npm run db:seed\`, not this one.
--
-- Safe to run more than once. Demo people are fictional; their accounts cannot
-- be signed in to: each gets a random password that is never stored anywhere,
-- and the .example addresses are reserved and receive no mail.

insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
)
select
  '00000000-0000-0000-0000-000000000000', demo.id, 'authenticated', 'authenticated',
  demo.email, extensions.crypt(gen_random_uuid()::text, extensions.gen_salt('bf')), now(),
  '{"provider": "email", "providers": ["email"]}'::jsonb,
  jsonb_build_object('name', demo.name), now(), now(), '', '', '', ''
from (values
${accounts}
) as demo (id, email, name)
on conflict (id) do nothing;

insert into auth.identities (
  id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at
)
select
  gen_random_uuid(), u.id, u.id::text, 'email',
  jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true),
  now(), now(), now()
from auth.users u
where u.email like '%@demo.roompair.example'
  and not exists (
    select 1 from auth.identities i where i.user_id = u.id and i.provider = 'email'
  );

-- The sign-up trigger has already created a bare profile for each account.
update public.profiles p set
  name = d.name, age = d.age, status = d.status, occupation = d.occupation,
  university = d.university, languages = d.languages, gender = d.gender,
  city = d.city, neighborhood = d.neighborhood, bio = d.bio,
  photo_url = d.photo_url, photos = d.photos, tags = d.tags, prompts = d.prompts,
  intent = d.intent, budget_min = d.budget_min, budget_max = d.budget_max,
  move_date = d.move_date, stay_months = d.stay_months,
  cleanliness = d.cleanliness, social = d.social, sleep = d.sleep,
  smokes = d.smokes, has_pets = d.has_pets, guests = d.guests,
  home_days = d.home_days, noise = d.noise, sharing = d.sharing,
  verified = d.verified, active = d.active,
  demo_likes_newcomers = d.demo_likes_newcomers, is_demo = true, onboarded = true
from (values
${people}
) as d (
  id, name, age, status, occupation, university, languages, gender, city,
  neighborhood, bio, photo_url, photos, tags, prompts, intent, budget_min,
  budget_max, move_date, stay_months, cleanliness, social, sleep, smokes,
  has_pets, guests, home_days, noise, sharing, verified, active,
  demo_likes_newcomers
)
where p.id = d.id;

insert into public.rooms (id, owner_id, title, price, city)
values
${roomKeys}
on conflict (id) do nothing;

update public.rooms r set
  title = d.title, description = d.description, price = d.price,
  photo_url = d.photo_url, photos = d.photos, city = d.city,
  neighborhood = d.neighborhood, bills_included = d.bills_included,
  deposit = d.deposit, private_bathroom = d.private_bathroom,
  furnished = d.furnished, flatmates = d.flatmates, transport = d.transport,
  house_rules = d.house_rules
from (values
${roomDetails}
) as d (
  id, title, description, price, photo_url, photos, city, neighborhood,
  bills_included, deposit, private_bathroom, furnished, flatmates, transport,
  house_rules
)
where r.id = d.id;
`;

writeFileSync(join(import.meta.dirname, "../../supabase/seed.sql"), sql);
console.log(
  `Wrote supabase/seed.sql: ${profiles.length} people, ${hosts.length} rooms.`,
);
